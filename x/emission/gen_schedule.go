//go:build ignore

// Regenerates schedule_table.go. Run from the repository root:
//
//	go run ./x/emission/gen_schedule.go
package main

import (
	"fmt"
	"os"
	"strings"

	"encryptlock/lockkeeper/x/emission"
)

func main() {
	var b strings.Builder
	b.WriteString("// Code generated by gen_schedule.go. DO NOT EDIT.\n\n")
	b.WriteString("package emission\n\n")
	b.WriteString("// MonthlyEmission is the lockunit released in each of the 360 months\n")
	b.WriteString("// (1 LOCK = 100.000.000 lockunit). See ComputeSchedule.\n")
	b.WriteString("var MonthlyEmission = [360]uint64{\n")
	for n, amount := range emission.ComputeSchedule() {
		fmt.Fprintf(&b, "\t%d, // month %d\n", amount, n+1)
	}
	b.WriteString("}\n")

	if err := os.WriteFile("x/emission/schedule_table.go", []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
}
